-- 1. 创建数据库（如果不存在）
CREATE DATABASE IF NOT EXISTS phrolova_game DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

-- 2. 使用数据库
USE phrolova_game;

-- 3. 创建角色表
DROP TABLE IF EXISTS characters;

CREATE TABLE characters (
    id          INT UNSIGNED    NOT NULL AUTO_INCREMENT COMMENT '主键,自增ID',
    name        VARCHAR(255)    NOT NULL                COMMENT '姓名',
    attribute   VARCHAR(50)     NOT NULL                COMMENT '属性',
    star_rating TINYINT UNSIGNED NOT NULL               COMMENT '星级',
    weapon      VARCHAR(50)     NOT NULL                COMMENT '武器',
    birthplace  VARCHAR(100)    NOT NULL                COMMENT '出生地',
    version     DOUBLE          NOT NULL                COMMENT '实装版本',
    PRIMARY KEY (id),
    UNIQUE KEY uk_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='角色数据表';

-- 3.1 创建玩家表（排行榜 / 得分）
DROP TABLE IF EXISTS players;

CREATE TABLE players (
    id          INT UNSIGNED    NOT NULL AUTO_INCREMENT COMMENT '主键,自增ID',
    player_id   VARCHAR(64)     NOT NULL                COMMENT '玩家ID(每设备唯一)',
    score       INT             NOT NULL DEFAULT 0      COMMENT '玩家总分',
    PRIMARY KEY (id),
    UNIQUE KEY uk_player_id (player_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='玩家得分表';

